from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path
from typing import Any


FAMILY_LABELS = {
    "openai": "OpenAI",
    "anthropic": "Anthropic",
    "google": "Google",
    "deepseek": "DeepSeek",
    "qwen": "Qwen",
    "meta": "Llama",
}


def _read_jsonl(path: Path) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    with path.open("r", encoding="utf-8") as handle:
        for line_no, line in enumerate(handle, start=1):
            if not line.strip():
                continue
            row = json.loads(line)
            if not isinstance(row, dict):
                raise ValueError(f"{path}:{line_no}: expected JSON object")
            rows.append(row)
    if not rows:
        raise ValueError(f"{path} contains no rows")
    return rows


def _fmt(value: object, digits: int = 3) -> str:
    if value is None:
        return "--"
    return f"{float(value):.{digits}f}"


def _fmt_p(value: object) -> str:
    if value is None:
        return "--"
    p = float(value)
    return "$<.001$" if p < 0.001 else f"{p:.3f}"


def _escape(text: object) -> str:
    return str(text).replace("_", "\\_")


def _index(rows: list[dict[str, Any]]) -> dict[tuple[str, str, str, str], dict[str, Any]]:
    out: dict[tuple[str, str, str, str], dict[str, Any]] = {}
    for row in rows:
        key = (
            str(row["rq"]),
            str(row["contrast"]),
            str(row["dataset"]),
            str(row["model_family"]),
        )
        metric = str(row["metric"])
        composite = (*key, metric)
        if composite in out:
            raise ValueError(f"duplicate inference row for {composite}")
        out[composite] = row
    return out


def _rq1_rows(rows: list[dict[str, Any]]) -> list[str]:
    idx = _index(rows)
    keys = sorted(
        {
            (dataset, family)
            for rq, contrast, dataset, family, metric in idx
            if rq == "RQ1" and contrast == "observed_vs_demographic_counterfactual"
        }
    )
    output = []
    for dataset, family in keys:
        ndcg = idx.get(("RQ1", "observed_vs_demographic_counterfactual", dataset, family, "ndcg"))
        recall = idx.get(("RQ1", "observed_vs_demographic_counterfactual", dataset, family, "recall"))
        invalid = idx.get(("RQ1", "observed_vs_demographic_counterfactual", dataset, family, "invalid_rate"))
        if ndcg is None:
            continue
        output.append(
            "{} & {} & {} [{} , {}] & {} & {} & {} & {} \\\\".format(
                _escape(dataset),
                FAMILY_LABELS.get(family, _escape(family)),
                _fmt(ndcg.get("mean_paired_difference")),
                _fmt(ndcg.get("bootstrap_ci_low")),
                _fmt(ndcg.get("bootstrap_ci_high")),
                _fmt(None if recall is None else recall.get("mean_paired_difference")),
                _fmt(None if invalid is None else invalid.get("mean_paired_difference")),
                _fmt_p(ndcg.get("holm_adjusted_p")),
                _fmt(ndcg.get("matched_rank_biserial")),
            )
        )
    return output


def _rq2_rows(rows: list[dict[str, Any]]) -> list[str]:
    idx = _index(rows)
    contrast = "true_vs_shuffled_personality"
    keys = sorted(
        {
            (dataset, family)
            for rq, c, dataset, family, metric in idx
            if rq == "RQ2" and c == contrast
        }
    )
    output = []
    for dataset, family in keys:
        ndcg = idx.get(("RQ2", contrast, dataset, family, "ndcg"))
        recall = idx.get(("RQ2", contrast, dataset, family, "recall"))
        invalid = idx.get(("RQ2", contrast, dataset, family, "invalid_rate"))
        if ndcg is None:
            continue
        output.append(
            "{} & {} & {} [{} , {}] & {} & {} & {} & {} \\\\".format(
                _escape(dataset),
                FAMILY_LABELS.get(family, _escape(family)),
                _fmt(ndcg.get("mean_paired_difference")),
                _fmt(ndcg.get("bootstrap_ci_low")),
                _fmt(ndcg.get("bootstrap_ci_high")),
                _fmt(None if recall is None else recall.get("mean_paired_difference")),
                _fmt(None if invalid is None else invalid.get("mean_paired_difference")),
                _fmt_p(ndcg.get("holm_adjusted_p")),
                _fmt(ndcg.get("matched_rank_biserial")),
            )
        )
    return output


def render(rows: list[dict[str, Any]]) -> str:
    rq1 = _rq1_rows(rows)
    rq2 = _rq2_rows(rows)
    if not rq1 and not rq2:
        raise ValueError("inference rows contain neither supported RQ1 nor RQ2 summaries")

    parts = [
        "% AUTO-GENERATED by scripts/render_paper_results.py; DO NOT EDIT BY HAND.",
        "\\begin{table*}[t]",
        "\\centering",
        "\\caption{Dataset-level paired inference generated directly from the frozen FairEval analysis artifacts. CI = paired bootstrap confidence interval; $p_H$ = Holm-adjusted paired-permutation $p$-value; $r_{rb}$ = matched rank-biserial effect size.}",
        "\\label{tab:generated-rq12}",
        "\\scriptsize",
        "\\setlength{\\tabcolsep}{2.8pt}",
        "\\resizebox{\\textwidth}{!}{%",
        "\\begin{tabular}{llccccc}",
        "\\toprule",
        "\\multicolumn{7}{c}{\\textbf{Panel A: RQ1 observed demographic vs. matched demographic counterfactual}} \\\\",
        "\\cmidrule(lr){1-7}",
        "Dataset & Model & $\\Delta$ nDCG@10 [95\\% CI] & $\\Delta$ Recall@10 & $\\Delta$ invalid rate & $p_H$ & $r_{rb}$ \\\\",
        "\\midrule",
        *rq1,
        "\\midrule",
        "\\multicolumn{7}{c}{\\textbf{Panel B: RQ2 true measured personality vs. shuffled-profile control}} \\\\",
        "\\cmidrule(lr){1-7}",
        "Dataset & Model & $\\PVA_{nDCG}$ [95\\% CI] & $\\PVA_{Recall}$ & $\\Delta$ invalid rate & $p_H$ & $r_{rb}$ \\\\",
        "\\midrule",
        *rq2,
        "\\bottomrule",
        "\\end{tabular}}",
        "\\end{table*}",
        "",
    ]
    return "\n".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Render dataset-level FairEval RQ1/RQ2 inference as an auditable LaTeX table"
    )
    parser.add_argument("--inference-jsonl", required=True)
    parser.add_argument(
        "--output",
        default="paper/generated/rq12_inference_table.tex",
        help="generated LaTeX destination",
    )
    args = parser.parse_args()

    rows = _read_jsonl(Path(args.inference_jsonl))
    text = render(rows)
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text, encoding="utf-8", newline="\n")
    print(output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
