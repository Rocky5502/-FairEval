from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any


FAMILY_ORDER = ("openai", "anthropic", "google", "deepseek", "qwen", "meta")
FAMILY_LABELS = {
    "openai": "OpenAI",
    "anthropic": "Anthropic",
    "google": "Google",
    "deepseek": "DeepSeek",
    "qwen": "Qwen",
    "meta": "Llama",
}


def _read_jsonl(path: Path) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    with path.open("r", encoding="utf-8") as handle:
        for line_no, line in enumerate(handle, start=1):
            if not line.strip():
                continue
            row = json.loads(line)
            if not isinstance(row, dict):
                raise ValueError(f"{path}:{line_no}: expected JSON object")
            rows.append(row)
    if not rows:
        raise ValueError(f"{path} contains no inference rows")
    return rows


def _fmt(value: object, digits: int = 3) -> str:
    if value is None:
        return "--"
    return f"{float(value):.{digits}f}"


def _p(value: object) -> str:
    if value is None:
        return "--"
    value = float(value)
    return "$<.001$" if value < 0.001 else f"{value:.3f}"


def _effect(row: dict[str, Any] | None) -> str:
    if row is None:
        return "--"
    return "{} [{}, {}]".format(
        _fmt(row.get("mean_paired_difference")),
        _fmt(row.get("bootstrap_ci_low")),
        _fmt(row.get("bootstrap_ci_high")),
    )


def render(rows: list[dict[str, Any]]) -> str:
    index: dict[tuple[str, str, str], dict[str, Any]] = {}
    for row in rows:
        if str(row.get("dataset")) != "fairsynth360" or str(row.get("metric")) != "ndcg":
            continue
        key = (str(row.get("rq")), str(row.get("contrast")), str(row.get("model_family")))
        if key in index:
            raise ValueError(f"duplicate FairSynth inference row: {key}")
        index[key] = row

    id_contrast = "observed_identity_vs_mean_counterfactual_identity"
    p_contrast = "true_synthetic_ocean_vs_shuffled_profile"
    lines: list[str] = []
    available = 0
    for family in FAMILY_ORDER:
        identity = index.get(("SYNTH-ID", id_contrast, family))
        personality = index.get(("SYNTH-PERSONALITY", p_contrast, family))
        if identity is not None or personality is not None:
            available += 1
        n_id = "--" if identity is None else str(int(identity["n_users"]))
        n_p = "--" if personality is None else str(int(personality["n_users"]))
        lines.append(
            "{} & {}/{} & {} & {} & {} & {} \\\\".format(
                FAMILY_LABELS[family],
                n_id,
                n_p,
                _effect(identity),
                _p(None if identity is None else identity.get("holm_adjusted_p")),
                _effect(personality),
                _p(None if personality is None else personality.get("holm_adjusted_p")),
            )
        )
    if available == 0:
        raise ValueError("no FairSynth nDCG inference rows found")

    return "\n".join(
        [
            "% AUTO-GENERATED by scripts/render_fairsynth_paper_results.py; DO NOT EDIT.",
            "\\begin{table}[t]",
            "\\centering",
            "\\caption{Hosted FairSynth-360 controlled sanity results. Identity $\\Delta$ compares the observed meaningless A/B/C label with the mean of its alternative identity labels; personality $\\Delta$ compares true synthetic OCEAN with a shuffled-profile control. Values are paired mean nDCG@10 differences [95\\% bootstrap CI] with Holm-adjusted paired-permutation $p_H$. $N_{ID}/N_P$ reports paired users available for the two contrasts. These synthetic controls are not pooled with real-world fairness or measured-psychometric claims.}",
            "\\label{tab:hosted-fairsynth-results}",
            "\\scriptsize",
            "\\setlength{\\tabcolsep}{2.4pt}",
            "\\resizebox{\\textwidth}{!}{%",
            "\\begin{tabular}{lccccc}",
            "\\toprule",
            "Model & $N_{ID}/N_P$ & Identity $\\Delta$ nDCG [95\\% CI] & $p_H$ & Personality $\\Delta$ nDCG [95\\% CI] & $p_H$ \\\\",
            "\\midrule",
            *lines,
            "\\bottomrule",
            "\\end{tabular}}",
            "\\end{table}",
            "",
        ]
    )


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Render hosted FairSynth inference directly into the ECIR LaTeX paper"
    )
    parser.add_argument("--inference-jsonl", required=True)
    parser.add_argument(
        "--output",
        default="paper/generated/fairsynth_hosted_table.tex",
    )
    args = parser.parse_args()

    rows = _read_jsonl(Path(args.inference_jsonl))
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(render(rows), encoding="utf-8", newline="\n")
    print(output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
